/**
 * Contract `bot-visit.v1` (docs/contracts/bot-visit.v1.md): the website
 * server reports one request from a known bot or crawler; the resolver stores
 * one row in `bot_visits` and answers `{version, recorded}`.
 *
 * A bot visit is never resolved, never associated with a company and never
 * counted as an entrance. The contract has no IP, no full user agent, no
 * cookie, header, referrer, session or visitor field, so none can be
 * accepted, forwarded or stored. The website decides what is a bot from its
 * own list (packages/tanstack/src/known-bots.ts); the resolver checks only the
 * shape of each value and the closed category set, so adding a bot to the
 * website's list needs no resolver change.
 */
import { API_VERSION } from "./api.js";

/** The only contract version this resolver accepts on POST /v1/bot-visits. */
export const BOT_VISIT_CONTRACT = "bot-visit.v1" as const;

/**
 * The closed category set. The website's bot list uses exactly these values. `ai_search` and `ai_assistant` were
 * added in migration 0014; packages released before then send `ai_crawler` for every AI bot, which stays valid.
 */
export const BOT_CATEGORIES = ["ai_crawler", "ai_search", "ai_assistant", "search_engine", "seo_tool", "social_preview", "monitoring", "other"] as const;
export type BotCategory = (typeof BOT_CATEGORIES)[number];

/** visit_id: random per visit, generated by the website server; the idempotency key of a retried delivery. */
export const BOT_VISIT_ID_PATTERN = /^[A-Za-z0-9_-]{16,64}$/;
/** bot_name: a name from the website's list, e.g. `GPTBot` or `Generic crawler`. No URL, no version, no free text. */
export const BOT_NAME_PATTERN = /^[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}$/;
/** user_agent_family: the one product token that identified the bot, without its version, e.g. `Googlebot-Image`. */
export const USER_AGENT_FAMILY_PATTERN = /^[A-Za-z0-9_][A-Za-z0-9_-]{0,63}$/;

/** The complete response: an acknowledgement only. `recorded: false` means this visit_id was already stored. */
export interface BotVisitResponse {
  version: typeof API_VERSION;
  recorded: boolean;
}

/** One accepted bot visit, as stored. installation_id and website_id come from deployment configuration. */
export interface BotVisitRecord {
  installationId: string;
  websiteId: string;
  visitId: string;
  observedAt: Date;
  pageKey: string;
  botName: string;
  botCategory: BotCategory;
  userAgentFamily: string;
}

/** One stored bot visit as the reporting API returns it (no visit_id, no installation or website id). */
export interface StoredBotVisit {
  id: number;
  observedAt: Date;
  pageKey: string;
  botName: string;
  botCategory: BotCategory;
  userAgentFamily: string;
}

/** Keyset position: rows strictly after (observed_at, id). */
export interface BotVisitCursor {
  observedAt: Date;
  id: number;
}

/**
 * Persistence for bot visits. The implementation (src/db/bot-visit-repo.ts)
 * issues statements on `bot_visits` only.
 */
export interface BotVisitRepository {
  /** Inserts the visit once per (installation, website, visit_id). true when this call stored it, false for a repeat. */
  record(visit: BotVisitRecord): Promise<boolean>;
  /** Visits observed in [from, to), ordered by (observed_at, id), strictly after `after` when given. */
  list(scope: { installationId: string; websiteId: string }, range: { from: Date; to: Date }, page: { after?: BotVisitCursor; limit: number }): Promise<StoredBotVisit[]>;
  /** One bounded retention batch: deletes at most `limit` visits received before `cutoff`. Returns rows deleted. */
  pruneBefore(cutoff: Date, limit: number): Promise<number>;
}
