/**
 * Supervisor <-> child IPC contract.
 *
 * Messages travel over the Node `fork()` IPC channel (in-memory pipe). The raw
 * IP and all secrets are passed ONLY through these messages, never through
 * argv or the environment. Both sides validate message shape before use.
 */
import type { CompanyContext, ResolutionSource, ResolutionStatus } from "./api.js";

export const IPC_PROTOCOL_VERSION = 1 as const;

/** Policy and secrets the child needs for exactly one job. */
export interface ChildRuntimeConfig {
  installation_id: string;
  website_id: string;
  key_version: number;
  /** Server-only HMAC secret (hex or base64url encoded as configured; child decodes). */
  ip_hmac_secret: string;
  database_url: string;
  /** TLS mode for the child's database pool; defaults to "require". Loopback hosts always use "disable". */
  database_ssl?: "require" | "disable" | "no-verify";
  provider: {
    mode: "live" | "mock" | "disabled";
    base_url: string;
    api_key: string;
    auth_header: string;
    timeout_ms: number;
  };
  policy: {
    ttl_qualified_ms: number;
    ttl_no_match_ms: number;
    ttl_excluded_ms: number;
    ttl_unknown_ms: number;
    ttl_provider_error_ms: number;
    ttl_uncertain_ms: number;
    lease_ms: number;
    /** Max time the child may wait for another worker's pending lookup. */
    pending_wait_ms: number;
    pending_poll_ms: number;
    period_call_cap: number;
    usage_period: "day" | "month";
    /** Usage-type codes that qualify a domain as an employer/organisation association. */
    qualified_usage_types: string[];
    /** Usage-type codes that mark the result as a network owner (never a company context). */
    excluded_usage_types: string[];
    /** Domains never returned as company context (case-insensitive exact match). */
    denied_domains: string[];
    /** Treat RFC 5737/3849 documentation ranges as eligible (tests only; default false). */
    allow_documentation_ranges?: boolean;
  };
  log_level: string;
}

export interface ChildConfigMessage {
  v: typeof IPC_PROTOCOL_VERSION;
  type: "config";
  config: ChildRuntimeConfig;
}

export interface ChildJobMessage {
  v: typeof IPC_PROTOCOL_VERSION;
  type: "job";
  job_id: string;
  /** Originating IP as received (already length-bounded by the API layer). */
  ip: string;
  /** Absolute wall-clock deadline (ms since epoch) by which the child must answer. */
  deadline_at_ms: number;
  /** Opaque idempotency reference for the observation this job may record (caller-supplied or generated by the supervisor). */
  observation_ref: string;
}

export type SupervisorToChildMessage = ChildConfigMessage | ChildJobMessage;

/** Durable activity outcome for a qualified resolution. Never carries an IP, a fingerprint or a payload. */
export interface ChildActivity {
  company_id: number;
  /** null when the write failed (unknown). */
  previously_seen: boolean | null;
  recorded: boolean;
  observation_ref: string;
}

export interface ChildOutcome {
  status: ResolutionStatus;
  company: CompanyContext | null;
  source: ResolutionSource;
  /** Allowlisted diagnostic reason for non-qualified outcomes; never free text from the provider. */
  reason?: ChildOutcomeReason;
  /** Present only for qualified outcomes. */
  activity?: ChildActivity;
}

export const CHILD_OUTCOME_REASONS = [
  "cache_fresh",
  "provider_resolved",
  "provider_no_domain",
  "provider_excluded_usage_type",
  "provider_unknown_usage_type",
  "provider_denied_domain",
  "provider_timeout",
  "provider_error_auth",
  "provider_error_credits",
  "provider_error_rate_limited",
  "provider_error_server",
  "provider_error_network",
  "provider_error_malformed",
  "pending_other_worker",
  "lease_lost",
  "cap_exhausted",
  "kill_switch",
  "provider_disabled",
  "ip_ineligible",
  "ip_invalid",
  "deadline_exceeded",
  "database_error",
  "internal_error",
  "activity_write_failed",
] as const;

export type ChildOutcomeReason = (typeof CHILD_OUTCOME_REASONS)[number];

export interface ChildReadyMessage {
  v: typeof IPC_PROTOCOL_VERSION;
  type: "ready";
}

export interface ChildResultMessage {
  v: typeof IPC_PROTOCOL_VERSION;
  type: "result";
  job_id: string;
  outcome: ChildOutcome;
}

export type ChildToSupervisorMessage = ChildReadyMessage | ChildResultMessage;

export function isChildToSupervisorMessage(value: unknown): value is ChildToSupervisorMessage {
  if (typeof value !== "object" || value === null) return false;
  const m = value as Record<string, unknown>;
  if (m["v"] !== IPC_PROTOCOL_VERSION) return false;
  if (m["type"] === "ready") return true;
  if (m["type"] === "result") {
    return typeof m["job_id"] === "string" && typeof m["outcome"] === "object" && m["outcome"] !== null;
  }
  return false;
}

export function isSupervisorToChildMessage(value: unknown): value is SupervisorToChildMessage {
  if (typeof value !== "object" || value === null) return false;
  const m = value as Record<string, unknown>;
  if (m["v"] !== IPC_PROTOCOL_VERSION) return false;
  if (m["type"] === "config") return typeof m["config"] === "object" && m["config"] !== null;
  if (m["type"] === "job") {
    return (
      typeof m["job_id"] === "string" &&
      typeof m["ip"] === "string" &&
      typeof m["deadline_at_ms"] === "number" &&
      typeof m["observation_ref"] === "string"
    );
  }
  return false;
}
