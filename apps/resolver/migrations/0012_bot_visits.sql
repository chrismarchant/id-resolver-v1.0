-- 0012: bot and crawler visits, contract bot-visit.v1. Forward-only and
-- additive: 0001-0011 are unchanged, and no existing table, trigger or feed
-- object is touched.
--
-- One row per request from a known bot or crawler, written only by
-- POST /v1/bot-visits (src/api/bot-visits.ts through src/db/bot-visit-repo.ts).
--   * No IP address, full user agent, cookie, header or referrer exists in
--     this table, so none can be stored. bot_name and user_agent_family are
--     short tokens (shape-checked here), never free text.
--   * Bot visits are never resolved or associated with companies: no
--     company, network-address, fingerprint or observation column, and no
--     foreign key to or from any other table.
--   * The table is not part of reporting-feed.v1: no feed position and no
--     trigger, so pruning it never moves the feed's retention watermark.
--
-- Retention: rows older than OBSERVATION_RETENTION_DAYS, by the resolver's
-- own received_at clock, are deleted by the bounded maintenance drain
-- (src/runtime/maintenance.ts), like browser_events.

CREATE TABLE IF NOT EXISTS bot_visits (
  id                 bigserial   PRIMARY KEY,
  installation_id    text        NOT NULL CHECK (installation_id ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
  website_id         text        NOT NULL CHECK (website_id ~ '^[a-z0-9][a-z0-9-]{0,62}$'),
  -- Random per visit, generated by the website server; makes a retried delivery idempotent.
  visit_id           text        NOT NULL CHECK (visit_id ~ '^[A-Za-z0-9_-]{16,64}$'),
  observed_at        timestamptz NOT NULL,
  -- Same rule as company_observations.page_key (0005): a normalised path only.
  page_key           text        NOT NULL
    CHECK (char_length(page_key) BETWEEN 1 AND 256 AND page_key ~ '^/[^?#[:space:][:cntrl:]]*$'),
  bot_name           text        NOT NULL CHECK (bot_name ~ '^[A-Za-z0-9][A-Za-z0-9 ._-]{0,63}$'),
  bot_category       text        NOT NULL
    CHECK (bot_category IN ('ai_crawler', 'search_engine', 'seo_tool', 'social_preview', 'monitoring', 'other')),
  user_agent_family  text        NOT NULL CHECK (user_agent_family ~ '^[A-Za-z0-9_][A-Za-z0-9_-]{0,63}$'),
  received_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT bot_visits_visit_unique UNIQUE (installation_id, website_id, visit_id)
);

-- Reporting reads one deployment scope by observed_at, in (observed_at, id) order.
CREATE INDEX IF NOT EXISTS bot_visits_report_idx
  ON bot_visits (installation_id, website_id, observed_at, id);

-- Retention: bounded batches delete the oldest rows first
-- (WHERE received_at < cutoff ORDER BY received_at, id LIMIT n).
CREATE INDEX IF NOT EXISTS bot_visits_retention_idx
  ON bot_visits (received_at, id);
